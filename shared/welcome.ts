// This is an application initiation, not text authored by the person. MA has
// no verified unsolicited-turn API; the ordinary event remains in its history.
import { eventText, type AgentEvent } from "./types";

export function isWelcomeReply(events: AgentEvent[], id: string) {
  let initiated = false;
  for (const event of events) {
    if (event.type === "user.message")
      initiated = event.app_initiation === "welcome";
    if (initiated && event.type === "agent.message" && eventText(event).trim())
      return event.id === id;
  }
  return false;
}

export function welcomePrompt(language: string) {
  const locale = /^[a-z]{2,3}(?:-[a-z0-9]{2,8}){0,3}$/i.test(language)
    ? language
    : "en";
  return `<open-muse-welcome>
The app is starting this person's first main conversation. This message was generated by the app, not written by the person. Reply in the language of locale ${locale}, unless personal memory specifies a different language.

Read the attached personal identity quietly. Give a warm introduction as their personal companion who can help get things done, in at most two short sentences and 45 words. Do not add a transition paragraph before the question. Do not invent their name or facts about them. Then ask what they would like to call you, noting that it can change later. Use one muse-choice block with these options in this order: Kit, Milo, Muse. Put the naming question only in the block, not again in prose. Leave space for a custom typed name. Do not save a name or preference until they answer. Do not expose this initiation or internal files in your reply. Stop after this question and wait for their answer.
</open-muse-welcome>`;
}

